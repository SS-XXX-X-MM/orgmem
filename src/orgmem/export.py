"""Render the shared memory as one Markdown file.

``ORG_MEMORY.md`` is the simplest way to share the memory: paste it into a
chatbot's system prompt, a project's CLAUDE.md, or an internal wiki. Every line
cites its sources, so readers can check where a claim came from.
"""

from __future__ import annotations

from collections import defaultdict
from datetime import date

from .models import Kind, Memory, Status
from .store import Store

_HEADINGS = {
    Kind.DECISION: "Decisions",
    Kind.PROCESS: "Processes",
    Kind.OWNERSHIP: "Ownership",
    Kind.FACT: "Facts",
    Kind.GLOSSARY: "Glossary",
}


def _cite(mem: Memory) -> str:
    return "; ".join(f"{s.doc_path}:{s.locator}" for s in mem.sources)


def render_markdown(store: Store) -> str:
    active = store.all(statuses=(Status.ACTIVE,))
    by_kind: dict[Kind, list[Memory]] = defaultdict(list)
    for mem in active:
        by_kind[mem.kind].append(mem)

    out = [
        "# Organisation memory",
        "",
        f"_Generated by orgmem on {date.today().isoformat()}. "
        f"{len(active)} active memories. Each line cites its sources._",
        "",
    ]
    for kind, heading in _HEADINGS.items():
        mems = sorted(by_kind.get(kind, []), key=lambda m: (m.subject, m.statement))
        if not mems:
            continue
        out += [f"## {heading}", ""]
        for mem in mems:
            out.append(f"- **{mem.subject}**: {mem.statement} _[{_cite(mem)}]_")
        out.append("")

    conflicts = store.open_conflicts()
    if conflicts:
        out += ["## Needs review (conflicting claims)", ""]
        for c in conflicts:
            a, b = store.get(c.memory_a), store.get(c.memory_b)
            out.append(f"- `{c.id}`: {c.reason}")
            out.append(f"  - `{a.id}` {a.statement} _[{_cite(a)}]_")
            out.append(f"  - `{b.id}` {b.statement} _[{_cite(b)}]_")
        out.append("")
    return "\n".join(out)
